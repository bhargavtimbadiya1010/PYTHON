'''2. Write a program to illustrate the use of different 
data types and type casting.'''

#Integer
x = 10
print("Value of x:", x)
print("Type of x:", type(x))
y = float(x)
print("Value of y:", y)
print("Type of y:", type(y))
print()

#Float
x = 12.6
print("Value of x:", x)
print("Type of x:", type(x))
y = int(x)
print("Value of y:", y)
print("Type of y:", type(y))
