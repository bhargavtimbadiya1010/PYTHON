import math as m

print('value of pi is:',m.pi)
print('square root of number 25 is:',m.sqrt(25))
print('factorial of number 5 is:',m.factorial(5))
print('power of number 3^5 is:',m.pow(3,5))
print('degrees of number 6 is:',m.degrees(6))
print('floor of number 87.5 is:',m.floor(87.5))
print('ceil of number 85.4 is:',m.ceil(85.4))
print('log10 of 100 is:',m.log10(100))


